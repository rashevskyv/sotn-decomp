"""Build text files into the program as C strings.

Apron patches: data/apron/<STAGE>.txt -> g_ApronBaked (src/pc/apron.c reads
them when the SD card or the PC disk has no apron/<STAGE>.txt). The same
script builds the editor page (tools/editor/index.html -> g_EditorPage).
The patches hold tile numbers only, no game graphics.

usage: bake_apron.py <out.c> <array name> [files...]
"""
import os
import sys


def c_string(data):
    out, line = [], '"'
    for b in data:
        c = chr(b)
        if c == "\n":
            out.append(line + '\\n"')
            line = '"'
        elif 32 <= b < 127 and c not in '"\\?':
            line += c
        else:
            line += "\\%03o" % b  # octal: never runs into the next char
    out.append(line + '"')
    return "\n        ".join(out)


def main():
    out, name, files = sys.argv[1], sys.argv[2], sorted(sys.argv[3:])
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out + ".tmp", "w") as f:
        f.write("// generated by tools/editor/bake_apron.py\n"
                "#include <game.h>\n\n"
                "const struct BakedFile %s[] = {\n" % name)
        for path in files:
            data = open(path, "rb").read()
            f.write('    {"%s",\n        %s,\n        %d},\n'
                    % (os.path.basename(path), c_string(data), len(data)))
        f.write("    {0, 0, 0},\n};\n")
        f.write("const int %sCount = %d;\n" % (name, len(files)))
    os.replace(out + ".tmp", out)
    print("%s: %d files -> %s" % (name, len(files), out))


if __name__ == "__main__":
    main()
