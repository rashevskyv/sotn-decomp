"""The Saturn's own hand items for the PC port (ITEM_ASTRAL_DAGGER.., include/items.h).

usage: saturn_items.py <saturn disc dir> <PS1 equipment.yaml> <out.h>

Each item takes the row of a PS1 stand-in (its weapon program, hand sprite, animation, special
move and icon: the PS1 has no code for the Saturn's weapons 61-63) and the Saturn's numbers from
GAME.PRG g_EquipDefs: attack, defence, element, critical rate, MP, stun, hit type and effect,
invincibility. The Saturn's icons of these four items in ITEM.CHR are its "未" placeholder (an
icon used many times), so the stand-in's stock icon stays. Without the disc the stand-in rows
stay whole (SATURN_ITEMS_FROM_DISC 0). The output is Konami's data: build dir only, never git.
"""
import os
import struct
import sys

import yaml

GAME_BASE = 0x06066000
EQUIP_DEFS = 0x0607C250  # GAME.PRG g_EquipDefs, 0x34 bytes each, big-endian
ROW = ">IIhhHBBBBBBBBBBBBBBIIHHHHHHH"

# (macro, Saturn hand item, PS1 stand-in) in item id order from 0xD9
ITEMS = (("ASTRAL_DAGGER", 174, 20),  # Combat knife
         ("KUSAI_MESHI", 70, 69),  # Turkey
         ("WOODLAND_SHIELD", 173, 5),  # Leather shield
         ("DOUBLE_BLADE_AXE", 175, 98))  # Claymore

FIELDS = ("attack", "defense", "element", "item_category", "weapon_id", "palette", "unknown_11",
          "player_anim", "unknown_13", "unknown_14", "lock_duration", "chain_limit", "unknown_17",
          "special_move", "is_consumable", "enemy_invincibility_frames", "unknown_1b", "combo_sub",
          "combo_main", "mp_usage", "stun_frames", "hit_type", "hit_effect", "icon", "icon_palette",
          "critical_rate")
# the Saturn's numbers; everything else is the stand-in's
FROM_SATURN = ("attack", "defense", "element", "enemy_invincibility_frames", "mp_usage",
               "stun_frames", "hit_type", "hit_effect", "critical_rate")
ELEMENTS = {"ELEMENT_HIT": 0x20, "ELEMENT_CUT": 0x40, "ELEMENT_POISON": 0x80, "ELEMENT_CURSE": 0x100,
            "ELEMENT_STONE": 0x200, "ELEMENT_WATER": 0x400, "ELEMENT_DARK": 0x800,
            "ELEMENT_HOLY": 0x1000, "ELEMENT_ICE": 0x2000, "ELEMENT_THUNDER": 0x4000,
            "ELEMENT_FIRE": 0x8000, "ELEMENT_UNK_1": 0x1, "ELEMENT_UNK_2": 0x2, "ELEMENT_UNK_4": 0x4,
            "ELEMENT_UNK_8": 0x8, "ELEMENT_UNK_10": 0x10}


def saturn_row(game, i):
    r = struct.unpack_from(ROW, game, EQUIP_DEFS - GAME_BASE + i * 0x34)
    return dict(zip(("name", "description") + FIELDS, r))


def ps1_row(r):
    out = dict(r)
    out["element"] = sum(ELEMENTS[e] for e in r.get("element") or [])
    out["is_consumable"] = int(bool(r["is_consumable"]))
    return out


def main():
    disc, yml, out = sys.argv[1:4]
    ps1 = [ps1_row(r) for r in yaml.safe_load(open(yml, encoding="utf-8"))]
    game_p = os.path.join(disc, "GAME.PRG")
    have = os.path.isfile(game_p)
    lines = ["// generated by tools/saturn/saturn_items.py: do not edit, do not commit",
             f"#define SATURN_ITEMS_FROM_DISC {int(have)}"]
    if have:
        game = open(game_p, "rb").read()
        # the self-check: the Saturn's hand items 0-69 are the PS1's 0-69 with the same numbers
        for i in range(70):
            s, p = saturn_row(game, i), ps1[i]
            for f in ("attack", "defense", "element", "critical_rate"):
                assert s[f] == p[f], f"Saturn item {i} {f} {s[f]} != PS1 {p[f]}: wrong table"
    for name, sat, stand in ITEMS:
        row = dict(ps1[stand])
        if have:
            s = saturn_row(game, sat)
            for f in FROM_SATURN:
                row[f] = s[f]
        vals = []
        for f in FIELDS:
            v = row[f]
            vals.append(v if f == "item_category" else
                        ("true" if v else "false") if f == "is_consumable" else
                        f"0x{v:08X}" if f.startswith("combo") else
                        f"0x{v:04X}" if f == "element" else str(v))
        lines.append(f"#define SATURN_EQUIP_{name} {', '.join(vals)}")
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"saturn_items: {'GAME.PRG' if have else 'no disc: stand-in rows'} -> {out}")


if __name__ == "__main__":
    main()
