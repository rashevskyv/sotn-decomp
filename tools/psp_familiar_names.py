"""The English names of the two Saturn familiars from the PSP disc (PSPBIN/dra.bin, pspeu).

The US data keeps their Japanese names; the PSP English menu table (D_psp_091C59C0, the
g_MenuStr rows) has English ones. This writes them as a C header in the build dir, so no
game text goes into git. Usage: psp_familiar_names.py <dra.bin> <config_us.h> <out.h>
"""
import os
import re
import struct
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "lang"))
import sotn_lang as L  # noqa: E402  (the sotn_str cell table and the US g_MenuStr reader)

VRAM, START = 0x090DCA00, 0x80  # config/splat.pspeu.dra.yaml: the dra segment
MENU_STR = 0x091C59C0  # D_psp_091C59C0: g_MenuStr in English
FIRST, OURS = 46, (51, 52)  # the familiar rows; 51 and 52 are the two Saturn ones


def cell_string(data, addr):
    off = addr - VRAM + START
    end = data.index(b"\xff", off)
    return data[off:end + 1]


def main():
    dra, cfg, out = sys.argv[1:4]
    data = open(dra, "rb").read()
    rows = [cell_string(data, struct.unpack_from("<I", data, MENU_STR - VRAM + START + 4 * k)[0])
            for k in range(FIRST, OURS[-1] + 1)]
    # The PSP table must hold the same bytes as the US build for the five stock familiars.
    L.TABLE, L.TABLE_INDEX = L.rust_table()
    us = L.us_branch(open(cfg, encoding="utf-8").read())
    us = [L.c_unescape(m.group(1)) for m in re.finditer(r"_S\(" + L.CSTR + r"\)", L.block_text(us, "g_MenuStr[] = {"))]
    for k in range(FIRST, OURS[0]):
        want = L.stock_bytes("cell", us[k])
        if rows[k - FIRST] != want:
            sys.exit(f"{dra}: row {k} is {rows[k - FIRST].hex()}, the US build has {want.hex()}")
    names = [rows[k - FIRST] for k in OURS]
    assert all(1 < len(n) <= 8 for n in names), names  # the familiar list has 7 cells per line
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by tools/psp_familiar_names.py from the PSP disc. Do not commit.\n")
        f.write("static const char psp_familiar_names[2][10] = {\n")
        for n in names:
            f.write('    "' + "".join("\\x%02X" % b for b in n) + '",\n')
        f.write("};\n")


if __name__ == "__main__":
    main()
