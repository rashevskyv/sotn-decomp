"""Writes the uk prologue scroll script as a C header.

usage: prologue_text.py <prologue.txt> <out .h>

The text is the project's own translation (tools/lang/uk/prologue.txt):
paragraphs split by a blank line, one scroll line a text line.
src/st/st0/3101C_psx.c draws it with the script loop of the English text:
a byte 0x80 + i is the glyph PROLOGUE_UK_MAP[i] (a Shift-JIS code, drawn
by func_80106A28 in the uk serif glyphs), 0x20 a space, then after each
line 1 (new line) or 2 (new paragraph) and the start column of the next
line. A glyph is 3 VRAM columns (12 px), a space 2; columns 0x38..0x3F
are the hidden gap between the two halves of the line, the script loop
jumps it. A line is centred on the 512 frame.
"""
import os
import sys

CUSTOM = {ch: 0x8540 + i for i, ch in enumerate("ҐЄЇґєї")}  # UK_SJIS_FIRST
SERIF = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЬЮЯабвгдежзийклмнопрстуфхцчшщьюя"
MARKS = {"І": 0x8268, "і": 0x8289, ",": 0x8143, ".": 0x8144, "’": 0x8166,
         "—": 0x815C, "-": 0x815D}
LAST_COL = 0x7C  # the right half of a line shows columns 0x40..0x7B


def code(ch):
    if ch in MARKS:
        return MARKS[ch]
    if ch in CUSTOM:
        return CUSTOM[ch]
    assert ch in SERIF, f"no prologue glyph for {ch!r}"
    return int.from_bytes(ch.encode("cp932"), "big")


def column(line):
    w = sum(8 if c == " " else 12 for c in line)
    return max(0, round((256 - w / 2 - 32) / 4))


def end_column(line):
    # the script loop of 3101C_psx.c
    x = column(line)
    for c in line:
        x += 2 if c == " " else 3
        if 0x38 <= x < 0x40:
            x += 8
    return x


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read().strip().replace("\r", "")
    paras = [p.split("\n") for p in text.split("\n\n")]
    lines = [(l, pi < len(paras) - 1 and li == len(p) - 1)
             for pi, p in enumerate(paras) for li, l in enumerate(p)]
    chars, script = [], bytearray()
    for i, (line, para_end) in enumerate(lines):
        assert end_column(line) <= LAST_COL, f"line {i + 1} too long: {line}"
        for ch in line:
            if ch == " ":
                script.append(0x20)
                continue
            if ch not in chars:
                code(ch)
                chars.append(ch)
            script.append(0x80 + chars.index(ch))
        if i + 1 < len(lines):
            script += bytes([2 if para_end else 1, column(lines[i + 1][0])])
    assert len(chars) <= 0x80, len(chars)
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as f:
        f.write("// generated by tools/lang/uk/prologue_text.py from prologue.txt\n")
        f.write("#define PROLOGUE_UK_COL0 %d\n" % column(lines[0][0]))
        f.write("static const u16 prologue_uk_map[] = {%s};\n"
                % ", ".join("0x%04X" % code(c) for c in chars))
        f.write("static const u8 prologue_uk_script[] = {%s, 0};\n"
                % ", ".join("0x%02X" % b for b in script))


if __name__ == "__main__":
    main()
